// /sw.js: the service worker that makes the site installable and readable offline.
//
// It is generated at build time so that it always knows the current list of pages
// (from src/data/pages.ts) and gets a new version stamp on every build. A new stamp
// is what tells browsers to replace the old saved copy of the site.
//
// How it treats each kind of request:
//   - Pages:            network first, so dates and deadlines are never stale while
//                       online. If the network fails, or takes longer than 5 seconds
//                       and a saved copy exists, the saved copy is shown instead.
//   - /_astro/ files:   saved copy first. Their names change whenever their content
//                       changes, so a saved copy can never be out of date.
//   - Everything else:  saved copy straight away, refreshed in the background.
import type { APIRoute } from 'astro';
import { allPages } from '../data/pages';

const worker = (version: string, pages: string[]) => `// Generated by src/pages/sw.js.ts. Do not edit this file directly.
const VERSION = ${JSON.stringify(version)};
const PAGES = ${JSON.stringify(pages)};
const OFFLINE_URL = '/offline/';
const SHELL = 'hpn-shell-' + VERSION; // pages, styles and fonts for this build
const ASSETS = 'hpn-assets-v1';       // images and other files, kept between builds
const ASSET_LIMIT = 160;
const PAGE_TIMEOUT = 5000;

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const shell = await caches.open(SHELL);
    // The offline page must be saved. Everything else is best effort.
    await shell.add(new Request(OFFLINE_URL, { cache: 'reload' }));
    await Promise.allSettled(PAGES.map((path) => shell.add(new Request(path, { cache: 'reload' }))));
    await Promise.allSettled(['/icon-192.png', '/favicon.ico', '/site.webmanifest'].map((path) => shell.add(path)));
    // Save the stylesheets, the fonts they load, and the logos used on every page.
    try {
      const wanted = new Set();
      for (const path of [OFFLINE_URL, ...PAGES]) {
        const saved = await shell.match(path);
        if (!saved) continue;
        const html = await saved.text();
        for (const m of html.matchAll(/href="(\\/_astro\\/[^"]+\\.css)"/g)) wanted.add(m[1]);
        for (const m of html.matchAll(/src="(\\/_astro\\/logo-[^"]+)"/g)) wanted.add(m[1]);
      }
      for (const url of [...wanted]) {
        const response = await fetch(url);
        if (!response.ok) continue;
        await shell.put(url, response.clone());
        if (!url.endsWith('.css')) continue;
        const css = await response.text();
        const fonts = [...css.matchAll(/url\\((\\/_astro\\/[^)]+\\.woff2)\\)/g)].map((m) => m[1]);
        await Promise.allSettled(fonts.map((font) => shell.add(font)));
      }
    } catch (error) {
      // Offline reading still works without these; they are saved on the next visit.
    }
    await self.skipWaiting();
  })());
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const names = await caches.keys();
    await Promise.all(names.filter((name) => name.startsWith('hpn-shell-') && name !== SHELL).map((name) => caches.delete(name)));
    if (self.registration.navigationPreload) await self.registration.navigationPreload.enable();
    await self.clients.claim();
  })());
});

async function trim(cache) {
  const keys = await cache.keys();
  for (const key of keys.slice(0, Math.max(0, keys.length - ASSET_LIMIT))) await cache.delete(key);
}

async function page(event) {
  const shell = await caches.open(SHELL);
  const saved = await shell.match(event.request, { ignoreSearch: true });
  const network = (async () => {
    const response = (await event.preloadResponse) || (await fetch(event.request));
    if (response.ok && !response.redirected) await shell.put(event.request, response.clone());
    return response;
  })();
  try {
    if (!saved) return await network;
    // A saved copy exists: give the network a few seconds, then stop waiting.
    const slow = new Promise((resolve) => setTimeout(() => resolve(null), PAGE_TIMEOUT));
    const response = await Promise.race([network, slow]);
    if (response) return response;
    network.catch(() => {});
    return saved;
  } catch (error) {
    return saved || (await shell.match(OFFLINE_URL)) || Response.error();
  }
}

async function savedFirst(request) {
  const saved = await caches.match(request);
  if (saved) return saved;
  const response = await fetch(request);
  if (response.ok) {
    const assets = await caches.open(ASSETS);
    await assets.put(request, response.clone());
    trim(assets);
  }
  return response;
}

async function savedThenRefresh(request) {
  const saved = await caches.match(request);
  const refresh = fetch(request).then(async (response) => {
    if (response.ok) {
      const assets = await caches.open(ASSETS);
      await assets.put(request, response.clone());
      trim(assets);
    }
    return response;
  });
  if (saved) {
    refresh.catch(() => {});
    return saved;
  }
  return refresh;
}

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin || url.pathname === '/sw.js') return;
  if (request.mode === 'navigate') event.respondWith(page(event));
  else if (url.pathname.startsWith('/_astro/')) event.respondWith(savedFirst(request));
  else event.respondWith(savedThenRefresh(request));
});
`;

export const GET: APIRoute = () => {
  const version = new Date().toISOString().replace(/[-:.TZ]/g, '').slice(0, 14);
  const body = worker(version, allPages.map((p) => p.path));
  return new Response(body, { headers: { 'Content-Type': 'text/javascript; charset=utf-8' } });
};
